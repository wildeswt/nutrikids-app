import {
  CreateReminderInputSchema,
  ReminderResponseSchema,
  type CreateReminderInput,
  type ReminderResponse,
  type ReminderStatus,
} from '@nutrikids/shared';
import { z } from 'zod';
import i18n from '../i18n/index.js';
import { authFetch, parseApiError } from './api.js';

/** Error returned by the reminders endpoints, keeping the HTTP status so screens can react to it. */
export class ReminderApiError extends Error {
  readonly status: number;

  constructor(message: string, status: number) {
    super(message);
    this.name = 'ReminderApiError';
    this.status = status;
  }
}

/**
 * `true` when the API rejected the reminder because the child has no active informed consent
 * (403). The API sends no error code, so the status is combined with the message text.
 */
export function isReminderConsentError(err: unknown): boolean {
  return (
    err instanceof ReminderApiError && err.status === 403 && /consentimiento/i.test(err.message)
  );
}

async function toApiError(response: Response, fallback: string): Promise<ReminderApiError> {
  const payload: unknown = await response.json().catch(() => ({}));
  return new ReminderApiError(parseApiError(payload, fallback).message, response.status);
}

/** Lists the reminders the user can see, soonest first (`GET /reminders`, max 200). */
export async function fetchReminders(
  filter: { childId?: string; status?: ReminderStatus } = {},
): Promise<ReminderResponse[]> {
  const query = new URLSearchParams();
  if (filter.childId) query.set('childId', filter.childId);
  if (filter.status) query.set('status', filter.status);
  const suffix = query.size > 0 ? `?${query.toString()}` : '';

  const response = await authFetch(`/reminders${suffix}`);
  if (!response.ok) {
    throw await toApiError(response, i18n.t('errors:reminders.fetch'));
  }

  const rawJson: unknown = await response.json();
  return z.array(ReminderResponseSchema).parse(rawJson);
}

/**
 * Creates a reminder (`POST /reminders`). The `id` is generated by the client, so resending the
 * same body is idempotent (the server answers 200 with the existing reminder).
 */
export async function createReminder(input: CreateReminderInput): Promise<ReminderResponse> {
  const validatedBody = CreateReminderInputSchema.parse(input);

  const response = await authFetch('/reminders', {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify(validatedBody),
  });
  if (!response.ok) {
    throw await toApiError(response, i18n.t('errors:reminders.create'));
  }

  const rawJson: unknown = await response.json();
  return ReminderResponseSchema.parse(rawJson);
}

/** Marks a reminder as done (`PATCH /reminders/:id/complete`, idempotent). */
export async function completeReminder(id: string): Promise<ReminderResponse> {
  const response = await authFetch(`/reminders/${id}/complete`, { method: 'PATCH' });
  if (!response.ok) {
    throw await toApiError(response, i18n.t('errors:reminders.complete'));
  }

  const rawJson: unknown = await response.json();
  return ReminderResponseSchema.parse(rawJson);
}
